    suspend fun addCoins(amount: Long) = playerDao.addCoins(amount)
    suspend fun updateFailures(count: Int) = playerDao.updateFailures(count)
    suspend fun incrementPlayTime(deltaSeconds: Long) = playerDao.incrementPlayTime(deltaSeconds)
    suspend fun setEyeCareFilter(active: Boolean) = playerDao.setEyeCareFilter(active)
    suspend fun getRandomQuiz(): EcoQuiz? = quizDao.getRandomQuiz()
    suspend fun updateProfile(profile: PlayerProfile) = playerDao.updateProfile(profile)
    suspend fun unlockZone(zoneId: String) = shelterDao.unlockZone(zoneId)

