        shelterDao.insertZones(DEFAULT_SHELTER_ZONES)
        quizDao.insertQuizzes(DEFAULT_ECO_QUIZZES)
        if (playerDao.getPlayerProfileDirect() == null) {
            playerDao.insertProfile(PlayerProfile())
        }
    }

